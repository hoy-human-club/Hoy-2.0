// Writes src/app/captureDates.ts (0031): for every page code with a capture, the day its
// docs/screenshots/<CODE>/es-1280.jpg was last committed (CAPTURED), and the date of the newest changelog
// entry whose `codes:` line names that code (CHANGED). The manual's Figure shows the capture date and
// flags "may be out of date" when the page changed after it was captured.
// Deterministic (git history only, no clock). In a shallow clone (CI checks out one commit, so every file
// would carry the same date) the committed file is kept as is.
// Usage: npm run capture-dates   (also a step of npm run build)
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = new URL('../', import.meta.url);
const OUT = new URL('src/app/captureDates.ts', ROOT);
const git = (...args) => execFileSync('git', args, { cwd: fileURLToPath(ROOT), encoding: 'utf8' }).trim();

let shallow = true;
try { shallow = git('rev-parse', '--is-shallow-repository') === 'true'; } catch { /* not a git checkout */ }
if (shallow) {
  console.log(`capture-dates: ${existsSync(OUT) ? 'shallow or missing git history — keeping src/app/captureDates.ts' : 'no git history — writing an empty map'}`);
  if (!existsSync(OUT)) writeFileSync(OUT, render({}, {}));
  process.exit(0);
}

const shots = new URL('docs/screenshots/', ROOT);
const captured = {};
for (const code of readdirSync(shots, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
  const file = `docs/screenshots/${code}/es-1280.jpg`;
  if (!existsSync(new URL(file, ROOT))) continue;
  const day = git('log', '-1', '--format=%cs', '--', file);
  if (day) captured[code] = day;
}

const changed = {};
const logDir = new URL('docs/changelog/', ROOT);
for (const f of readdirSync(logDir).filter((x) => /^\d{4}-.*\.md$/.test(x)).sort()) {
  const src = readFileSync(new URL(f, logDir), 'utf8');
  const date = src.match(/^date:\s*(\d{4}-\d{2}-\d{2})/m)?.[1];
  const codes = src.match(/^codes:\s*(.+)$/m)?.[1];
  if (!date || !codes) continue;
  for (const code of codes.split(/[\s,]+/).filter((c) => /^[A-Z]{1,4}-\d{2}[a-z]?$/.test(c))) if (!changed[code] || changed[code] < date) changed[code] = date;
}

writeFileSync(OUT, render(captured, changed));
console.log(`capture-dates: ${Object.keys(captured).length} captured codes, ${Object.keys(changed).length} codes in changelog`);

function render(cap, chg) {
  const obj = (o) => `{\n${Object.keys(o).sort().map((k) => `  '${k}': '${o[k]}',`).join('\n')}\n}`;
  return `// GENERATED by scripts/gen-capture-dates.mjs from git history — do not edit by hand.
/** Page code → day its docs/screenshots/<CODE>/es-1280.jpg was last committed. */
export const CAPTURED: Record<string, string> = ${obj(cap)};

/** Page code → date of the newest changelog entry whose \`codes:\` line names it. */
export const CHANGED: Record<string, string> = ${obj(chg)};

/** A capture may be out of date when its page changed (changelog) after the capture was committed. */
export function captureInfo(code: string | undefined): { captured?: string; stale: boolean } {
  if (!code) return { stale: false };
  const captured = CAPTURED[code];
  const changed = CHANGED[code];
  return { captured, stale: !!captured && !!changed && changed > captured };
}
`;
}
